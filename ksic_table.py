# Глобальная таблица для интерполяции
_KSIC_TABLE = Table2D(_BETA_GRID, _PSI_GRID, _KSIC_VALUES)


def ksic(psi: float, beta: float) -> float:
    """
    Возвращает коэффициент ξ_c по значениям ψ и β.

    * ψ задаётся в диапазоне от 0 до 3.5. Отрицательные значения приводят к исключению,
      значения больше 3.5 автоматически ограничиваются сверху.
    * β задаётся в диапазоне от 0 до 2. Отрицательные значения приводят к исключению,
      значения больше 2.0 автоматически ограничиваются сверху.
    * Интерполяция выполняется билинейно по табличным данным, считанным с графика.
    """

    if psi < 0:
        raise ValueError("ψ (psi) должно быть неотрицательным.")
    if beta < 0:
        raise ValueError("β (beta) должно быть неотрицательным.")

    psi_clamped = min(psi, _PSI_GRID[-1])
    beta_clamped = min(beta, _BETA_GRID[-1])

    return _KSIC_TABLE.lookup(beta_clamped, psi_clamped, interpolate=True, clamp=True)
